void onTouchBegin(GameModel& game, const TouchRecord& touch)
{
    std::vector<LogicNote*> candidates;

    for (LogicNote* topLevel : game.activeNotes) {
        if (!topLevel->isActiveForInput) {
            continue;
        }

        if (auto* tap = dynamic_cast<LogicTapNote*>(topLevel)) {
            if (ordinaryLaneTapMatchesTouch(game, touch, *tap)) {
                candidates.push_back(tap);
            }
            continue;
        }

        if (auto* hold = dynamic_cast<LogicHoldNote*>(topLevel)) {
            if (holdAcquisitionMatchesTouch(game, touch, *hold)) {
                candidates.push_back(hold);
            }
            continue;
        }

        if (auto* arc = dynamic_cast<LogicArcNote*>(topLevel)) {
            for (LogicArcTapNote* arcTap : arc->arcTaps) {
                if (spatiallyQualifiesArcTap(game, touch, *arc, *arcTap)) {
                    candidates.push_back(arcTap);
                }
            }
        }
    }

    std::sort(candidates.begin(), candidates.end(), byStartTimestamp);

    for (LogicNote* note : candidates) {
        if (auto* tap = dynamic_cast<LogicTapNote*>(note)) {
            if (tryJudgePointNote(game, *tap, touch.id)) {
                return;
            }
        }

        // Hold acquisition path follows for non-point candidates.
    }
}

