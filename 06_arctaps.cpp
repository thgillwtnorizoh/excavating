/*
 * CONFIRMED GameModel architecture around ~0x0EEC024.
 *
 * GameModel maintains a top-level active-note collection around +0xA0 and a
 * temporary candidate vector around +0xB8.
 *
 * On touch-begin, the candidate vector is first cleared. GameModel walks active
 * notes and handles note families differently:
 *
 *   ordinary LogicTapNote:
 *       filter using its lane/input identity
 *
 *   LogicHoldNote:
 *       filter using lane/input identity and Hold timing/contact conditions
 *
 *   LogicArcNote:
 *       iterate the parent's ArcTap vector at +0x120
 *       spatially test each ArcTap child
 *       push the ArcTap CHILD into the temporary candidate vector if qualified
 *
 * Therefore ArcTap does NOT enter the ordinary lane-note branch as an independent
 * top-level note. It is discovered spatially through its parent Arc.
 */

// The temporary vector insertion helper is a normal pointer-vector push_back.
void addCandidate(std::vector<LogicNote*>& candidates, LogicNote* note)
{
    candidates.push_back(note);
}

// -----------------------------------------------------------------------------
// 6. ArcTap has a real sky/gameplay-space hit-region gate
// -----------------------------------------------------------------------------

/*
 * CONFIRMED touch-begin ArcTap filtering:
 *
 * For each child in LogicArcNote +0x120, GameModel:
 *   - copies the child's cached 12-byte point from +0x80
 *   - combines it with the parent Arc's gameplay horizontal anchor/transform
 *   - transforms current touch coordinates into the same gameplay-space frame
 *   - calls the common camera-scaled hit-region helper around ~0x0927384
 *
 * The helper receives:
 *
 *   nominal size value = 212.0f
 *   mode flag          = 1 for ArcTap
 *
 * Section 04's ordinary Arc-body contact calls the SAME helper with mode flag 0.
 * The mode flag alters internal bound construction, so this file deliberately
 * does NOT claim that final ArcTap and Arc-body rectangles are identical.
 *
 * The safe gameplay statement is:
 *
 *   ArcTap must be spatially near its precomputed point in sky/gameplay space
 *   before it is allowed into the timing-candidate list.
 *
 * It is NOT merely "any touch anywhere at the correct timestamp".
 */
bool spatiallyQualifiesArcTap(
    GameModel& game,
    const TouchRecord& touch,
    LogicArcNote& parent,
    LogicArcTapNote& tap)
{
    const auto expected =
        convertArcTapCachedPointToHitTestPoint(parent, tap.cachedPathPoint);

    const auto finger = transformTouchToGameplaySpace(game, touch);

    return cameraScaledHitRegionTest(
        game,
        finger,
        expected,
        212.0f,
        /* arcTapMode */ true);
}

