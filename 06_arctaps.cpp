// 9. ArcTap overrides successful-hit acceptance
// -----------------------------------------------------------------------------

/*
 * CONFIRMED ArcTap virtual override around ~0x0C78814.
 *
 * After optional feedback/audio work that is outside this gameplay slice, the
 * hook does the same essential local resolution as LogicTapNote:
 *
 *   ArcTap +0x0D = 1
 *   ArcTap +0x10 = input payload/touch identifier
 *
 * It then consults the object at +0x90 and reads that object's +0xA4 mode.
 *
 *   no parent pointer      -> accept
 *   parent mode != 2       -> accept
 *   parent mode == 2       -> veto ScoreState acceptance
 *
 * IMPORTANT ordering:
 * Local ArcTap hit state is written BEFORE the mode-2 veto is returned.
 * Therefore mode 2 resolves the ArcTap locally but prevents ScoreState from
 * treating that local hit as a score/gauge judgement.
 */
bool LogicArcTapNote_acceptSuccessfulHit(
    LogicArcTapNote& tap,
    int judgementTimeMs,
    int inputPayload)
{
    (void)judgementTimeMs;

    // Optional ArcTap feedback/audio path omitted.

    tap.hit = true;
    tap.inputPayload = inputPayload;

    if (tap.parentArc == nullptr) {
        return true;
    }

    return tap.parentArc->arcBodyMode != 2;
}

