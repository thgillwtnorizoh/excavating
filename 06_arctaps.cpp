// -----------------------------------------------------------------------------
// 3. ArcTap timestamp -> normalized parent-Arc progress
// -----------------------------------------------------------------------------

/*
 * CONFIRMED in the Arc path builder around ~0x1925084.
 *
 * The parent LogicArcNote iterates its child vector at +0x120 and evaluates each
 * ArcTap at the child's point timestamp.
 *
 * The normalized progress is mechanically:
 *
 *   t = (arcTapTime - parentArcStart)
 *       / (effectivePathEnd - parentArcStart)
 *
 * In the ordinary case effectivePathEnd == parentArc.endTime.
 *
 * Section 05 established one wrinkle: a related-pointer vector around parent
 * +0x138 can extend effectivePathEnd to the maximum of the Arc's own end time
 * and selected related objects' start times. The exact semantic identity of
 * that related-vector remains UNRESOLVED.
 *
 * Therefore do NOT simplify the native builder universally to denominator
 * parent.endTime-parent.startTime, although that is the normal case.
 */
float normalizedArcTapProgress(
    const LogicArcNote& parent,
    const LogicArcTapNote& tap,
    int32_t effectivePathEndMs)
{
    return float(tap.startTimeMs - parent.startTimeMs)
         / float(effectivePathEndMs - parent.startTimeMs);
}

// -----------------------------------------------------------------------------
// 4. ArcTap position is evaluated by the SAME parent Arc easing machinery
// -----------------------------------------------------------------------------

/*
 * CONFIRMED:
 *
 * After calculating normalized t, the path builder dispatches through the same
 * easing branch established in Section 05:
 *
 *   s / b / si / so / sisi / sosi / siso / soso
 *
 * `b` uses the dedicated cubic helper.
 * The other classic types use the straight/sinusoidal evaluator.
 *
 * The resulting 12-byte Vec3-like value is copied directly into:
 *
 *   ArcTap +0x80 .. +0x8B
 *
 * Representative native stores are equivalent to:
 *
 *   *(uint64_t*)(tap + 0x80) = result.firstEightBytes;
 *   *(uint32_t*)(tap + 0x88) = result.lastFourBytes;
 *
 * This is a precomputed spatial placement. Touch-begin later consumes this
 * cached point rather than rerunning AFF easing from scratch.
 */
ArcTapPathPoint evaluateArcTapPoint(
    const LogicArcNote& parent,
    int32_t arcTapTimeMs,
    int32_t effectivePathEndMs)
{
    const float t =
        float(arcTapTimeMs - parent.startTimeMs)
        / float(effectivePathEndMs - parent.startTimeMs);

    return evaluateParentArcPath(parent, t); // Section 05 formulas
}

void cacheArcTapPoints(LogicArcNote& parent, int32_t effectivePathEndMs)
{
    for (LogicArcTapNote* tap : parent.arcTaps) {
        tap->cachedPathPoint =
            evaluateArcTapPoint(parent, tap->startTimeMs, effectivePathEndMs);
    }
}

