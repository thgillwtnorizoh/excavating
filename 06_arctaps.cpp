// 7. Candidate ordering is by note timestamp
// -----------------------------------------------------------------------------

/*
 * CONFIRMED:
 * Before trying the temporary candidates, GameModel sorts the pointer vector.
 * The comparator repeatedly reads note +0x18 and orders by start timestamp.
 *
 * GameModel then walks the sorted candidates. A candidate dynamically castable
 * to LogicTapNote is passed directly to the point-note timing routine around
 * ~0x160CE28. Processing stops when that routine reports that the touch was
 * consumed/accepted as a timing attempt.
 *
 * ArcTap inherits LogicTapNote, so no ArcTap-specific timing-candidate function
 * is inserted between candidate selection and point judgement.
 */
void processTouchCandidates(
    GameModel& game,
    std::vector<LogicNote*>& candidates,
    int touchId)
{
    std::sort(candidates.begin(), candidates.end(),
        [](LogicNote* a, LogicNote* b) {
            return a->startTimeMs < b->startTimeMs;
        });

    for (LogicNote* note : candidates) {
        if (LogicTapNote* tap = dynamic_cast<LogicTapNote*>(note)) {
            if (tryJudgePointNote(game, *tap, touchId)) {
                return;
            }
        }

        // Hold-specific handling follows if the tap cast did not handle it.
    }
}

