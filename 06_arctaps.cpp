bool LogicArcTapNote_acceptLost(LogicArcTapNote& tap)
{
    tap.lost = true;

    if (tap.parentArc == nullptr) {
        return true;
    }

    return tap.parentArc->arcBodyMode != 2;
}

// -----------------------------------------------------------------------------
// 12. Automatic ArcTap miss scheduling is parent-Arc-owned
// -----------------------------------------------------------------------------

/*
 * CONFIRMED in the common gameplay update around ~0x0F8056C.
 *
 * After identifying a LogicArcNote, the update explicitly walks:
 *
 *   Arc +0x120 child vector
 *
 * For each ArcTap child:
 *   - call inherited virtual LOST-flag predicate
 *   - call inherited virtual hit-flag predicate
 *   - skip already resolved children
 *   - compare effective gameplay time against child endTime + 100 ms
 *
 * If:
 *
 *   effectiveTime > arcTap.endTime + 100
 *
 * it calls the ordinary ScoreState LOST entry path for that ArcTap child.
 *
 * Since LogicTapNote uses startTime == endTime, this is conceptually:
 *
 *   effectiveTime > arcTapTime + 100 ms
 *
 * The comparison is strictly greater-than at this scheduling branch.
 *
 * This also sharpens Section 02's timing caveat: the point-input routine has a
 * 101..120 ms LOST candidate band, while normal gameplay scheduling can already
 * auto-LOST an unresolved ArcTap once update time is later than +100 ms.
 * Exact event/update ordering determines whether every theoretical late-side
 * input value is reachable in every frame situation.
 */
void updateArcTapAutomaticMisses(
    GameModel& game,
    LogicArcNote& parent,
    int effectiveTimeMs,
    ScoreState& score)
{
    for (LogicArcTapNote* tap : parent.arcTaps) {
        if (tap->lost || tap->hit) {
            continue;
        }

        if (effectiveTimeMs > tap->endTimeMs + 100) {
            registerLost(score, *tap, effectiveTimeMs);
        }
    }
}

